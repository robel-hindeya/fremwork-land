// Writes supabase/setup/full-setup.sql: every migration in order, as one script for the
// Supabase SQL Editor on a NEW, EMPTY project. Run: pnpm db:setup-sql
// For a project that already has some migrations, apply only the missing files instead.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'supabase/migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const header = `-- Fremwork: complete database setup for a NEW, EMPTY Supabase project (Free plan compatible).
-- GENERATED by scripts/build-setup-sql.mjs from supabase/migrations. Do not edit by hand.
--
-- Paste into Supabase → SQL Editor → Run, once. It is not meant to be re-run, and it must not be
-- run on a project that already has the Fremwork tables (apply the missing migration files there).
-- Contains no sample data (see supabase/seed.sql) and no secrets.
--
-- Afterwards, in the SQL Editor:
--   select vault.create_secret('https://<project-ref>.supabase.co', 'project_url', 'Base URL for Edge Function webhooks');
-- Migrations included (${files.length}): ${files.join(', ')}
`;
const body = files.map((f) => `\n-- ═══ ${f} ${'═'.repeat(Math.max(0, 80 - f.length))}\n${readFileSync(path.join(dir, f), 'utf8').trim()}\n`).join('');
mkdirSync(path.join(root, 'supabase/setup'), { recursive: true });
writeFileSync(path.join(root, 'supabase/setup/full-setup.sql'), header + body);
console.log(`Wrote supabase/setup/full-setup.sql from ${files.length} migrations.`);
